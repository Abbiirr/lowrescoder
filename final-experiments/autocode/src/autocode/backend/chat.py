"""Host-independent backend chat execution helpers.

This module owns the substantive chat-turn execution path so ``BackendServer``
can stay focused on host coordination and transport concerns.
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import logging
from pathlib import Path
from typing import Any, Protocol

from autocode.agent.loop import AgentLoop
from autocode.backend import schema as rpc_schema
from autocode.backend import services as backend_services
from autocode.core.logging import log_event, setup_session_logging

logger = logging.getLogger(__name__)

_CHAT_HEARTBEAT_INTERVAL_S = 15.0


class ChatHost(Protocol):
    """Host surface required by the backend chat service."""

    config: Any
    project_root: Path
    session_store: Any
    session_id: str
    session_log_dir: Path
    session_titled: bool
    session_stats: Any | None
    session_approved_tools: set[str]
    approval_manager: Any | None
    context_assembler: Any
    l3_provider: Any
    task_store: Any | None
    subagent_manager: Any | None
    edit_count: int
    show_thinking: bool

    def emit_notification(self, method: str, params: dict[str, Any]) -> None: ...

    async def emit_request(self, method: str, params: dict[str, Any]) -> dict[str, Any]: ...

    def emit_cost_update(self) -> None: ...

    async def teardown_agent_resources(self) -> None: ...

    def ensure_agent_loop(self) -> AgentLoop: ...

    def expand_file_mentions(self, message: str) -> str: ...

    def select_chat_layer(self, message: str) -> tuple[int, str, bool]: ...


def on_chunk(host: ChatHost, text: str) -> None:
    """Stream token callback -> notification on_token."""
    host.emit_notification("on_token", {"text": text})


def on_thinking_chunk(host: ChatHost, text: str) -> None:
    """Thinking token callback -> notification on_thinking."""
    host.emit_notification("on_thinking", {"text": text})


def emit_warning(host: ChatHost, message: str) -> None:
    """Visible non-fatal warning notification for the frontend."""
    host.emit_notification(rpc_schema.METHOD_ON_WARNING, {"message": message})


def emit_cost_limit_warning(host: ChatHost) -> None:
    """Emit a pending cost-limit warning generated by the token tracker."""
    stats = host.session_stats
    tracker = getattr(stats, "token_tracker", None) if stats else None
    pop_warning = getattr(tracker, "pop_cost_limit_warning", None)
    if not callable(pop_warning):
        return
    warning = pop_warning()
    if warning is None:
        return
    total_usd, threshold_usd = warning
    emit_warning(
        host,
        "Session cost limit reached: "
        f"${total_usd:.4f} / ${threshold_usd:.4f} threshold. "
        "Continuing; use /cost to view.",
    )


def emit_task_state(host: ChatHost) -> None:
    """Emit the canonical task/subagent projection notification."""
    payload = backend_services.build_task_state_payload(
        task_store=host.task_store,
        subagent_manager=host.subagent_manager,
    )
    host.emit_notification(rpc_schema.METHOD_ON_TASK_STATE, payload)


SEARCH_RESULT_TOOLS = {"search_text", "grep_content", "search_code", "semantic_search"}
DIFF_RESULT_TOOLS = {"git_diff", "write_file", "edit_file", "apply_patch", "multi_edit"}


def _parse_search_result_payload(tool_name: str, result: str) -> dict[str, Any] | None:
    hits: list[dict[str, Any]] = []
    pending_markdown_hit: tuple[str, int] | None = None

    for raw_line in result.splitlines():
        line = raw_line.strip()
        if not line or line == "```":
            continue
        if line.startswith("**") and "**" in line[2:]:
            target = line[2:].split("**", 1)[0]
            parsed = _parse_path_line(target)
            if parsed is not None:
                pending_markdown_hit = parsed
            continue
        if pending_markdown_hit is not None:
            path, line_no = pending_markdown_hit
            hits.append({"path": path, "line": line_no, "snippet": line})
            pending_markdown_hit = None
            continue
        parsed_colon = _parse_colon_search_line(line)
        if parsed_colon is not None:
            path, line_no, snippet = parsed_colon
            hits.append({"path": path, "line": line_no, "snippet": snippet})

    if not hits:
        return None
    return {"kind": "search", "query": tool_name, "hits": hits}


def _parse_path_line(target: str) -> tuple[str, int] | None:
    if ":" not in target:
        return None
    path, line_no_text = target.rsplit(":", 1)
    try:
        line_no = int(line_no_text.strip())
    except ValueError:
        return None
    path = path.strip()
    if not path:
        return None
    return path, line_no


def _parse_colon_search_line(line: str) -> tuple[str, int, str] | None:
    parts = line.split(":", 2)
    if len(parts) != 3:
        return None
    path, line_no_text, snippet = (part.strip() for part in parts)
    try:
        line_no = int(line_no_text)
    except ValueError:
        return None
    if not path or not snippet:
        return None
    return path, line_no, snippet


def _parse_diff_result_payload(tool_name: str, result: str) -> dict[str, Any] | None:
    files: list[dict[str, Any]] = []
    current: dict[str, Any] | None = None
    in_diff_block = False

    for raw_line in result.splitlines():
        line = raw_line.rstrip()
        if line.strip() == "```diff":
            in_diff_block = True
            continue
        if line.strip() == "```":
            in_diff_block = False
            continue

        is_diff_line = (
            in_diff_block
            or line.startswith("diff --git ")
            or line.startswith("--- ")
            or line.startswith("+++ ")
            or line.startswith("@@")
            or (current is not None and (line.startswith("+") or line.startswith("-")))
        )
        if not is_diff_line:
            continue

        path = _parse_diff_git_path(line) or _parse_diff_new_path(line)
        if path is not None:
            if current is not None and current["path"] != path:
                files.append(current)
            if current is None or current["path"] != path:
                current = {"path": path, "added": 0, "removed": 0, "hunks": []}
            continue

        if current is None:
            continue

        hunks = current["hunks"]
        if line.startswith("@@"):
            hunks.append(line)
        elif line.startswith("+++") or line.startswith("---"):
            continue
        elif line.startswith("+"):
            current["added"] += 1
            if len(hunks) < 8:
                hunks.append(line)
        elif line.startswith("-"):
            current["removed"] += 1
            if len(hunks) < 8:
                hunks.append(line)

    if current is not None:
        files.append(current)

    if not files:
        return None
    return {"kind": "diff", "source": tool_name, "files": files}


def _parse_diff_git_path(line: str) -> str | None:
    if not line.startswith("diff --git "):
        return None
    rest = line[len("diff --git "):]
    parts = rest.split(" ", 1)
    if len(parts) != 2:
        return None
    return _strip_diff_path_prefix(parts[1])


def _parse_diff_new_path(line: str) -> str | None:
    if not line.startswith("+++ "):
        return None
    rest = line[len("+++ "):]
    if rest == "/dev/null":
        return None
    return _strip_diff_path_prefix(rest)


def _strip_diff_path_prefix(path: str) -> str:
    return path.removeprefix("b/").removeprefix("a/")


def build_tool_result_payload(tool_name: str, status: str, result: str) -> dict[str, Any] | None:
    if status not in ("completed", "success"):
        return None
    if tool_name in SEARCH_RESULT_TOOLS:
        return _parse_search_result_payload(tool_name, result)
    if tool_name in DIFF_RESULT_TOOLS:
        return _parse_diff_result_payload(tool_name, result)
    return None


def on_tool_call(host: ChatHost, tool_name: str, status: str, result: str = "") -> None:
    """Tool call status callback -> notification on_tool_call."""
    payload: dict[str, Any] = {
        "name": tool_name,
        "status": status,
        "result": result,
    }
    result_payload = build_tool_result_payload(tool_name, status, result)
    if result_payload is not None:
        payload["result_payload"] = result_payload
    host.emit_notification("on_tool_call", payload)
    if status in ("completed", "success") and tool_name in ("write_file", "edit_file"):
        host.edit_count += 1

    task_tools = {"create_task", "update_task", "add_task_dependency", "list_tasks"}
    if tool_name in task_tools and status in ("completed", "success"):
        emit_task_state(host)


async def approval_callback(host: ChatHost, tool_name: str, arguments: dict[str, Any]) -> bool:
    """Approval callback -> request on_tool_request, waits for frontend response."""
    if tool_name in host.session_approved_tools:
        on_tool_call(host, tool_name, "pending", "(auto-approved)")
        if tool_name == "run_command" and host.approval_manager:
            host.approval_manager.enable_shell()
        return True

    args_str = json.dumps(arguments, indent=2)
    try:
        result = await host.emit_request(
            rpc_schema.METHOD_ON_TOOL_REQUEST,
            {
                "tool": tool_name,
                "args": args_str,
            },
        )
    except asyncio.CancelledError:
        return False

    approved = result.get("approved", False)
    session_approve = result.get("session_approve", False)

    if approved and session_approve:
        host.session_approved_tools.add(tool_name)

    if approved and tool_name == "run_command" and host.approval_manager:
        host.approval_manager.enable_shell()

    return bool(approved)


async def ask_user_callback(
    host: ChatHost,
    question: str,
    options: list[str],
    allow_text: bool,
) -> str:
    """Ask-user callback -> request on_ask_user, waits for frontend response."""
    try:
        result = await host.emit_request(
            rpc_schema.METHOD_ON_ASK_USER,
            {
                "question": question,
                "options": options,
                "allow_text": allow_text,
            },
        )
    except asyncio.CancelledError:
        return options[0] if options else ""

    return result.get("answer", "")


def _emit_chat_ack(host: ChatHost, request_id: int) -> None:
    host.emit_notification(
        rpc_schema.METHOD_ON_CHAT_ACK,
        {
            "request_id": request_id,
            "session_id": host.session_id,
        },
    )


def _done_params(host: ChatHost, layer_used: int, *, cancelled: bool = False) -> dict[str, Any]:
    params: dict[str, Any] = {"layer_used": layer_used}
    if cancelled:
        params["cancelled"] = True
    if host.session_stats:
        tokens = host.session_stats.token_tracker.total
        params["tokens_in"] = tokens.prompt_tokens
        params["tokens_out"] = tokens.completion_tokens
        params["session_summary"] = host.session_stats.summary()
    else:
        params["tokens_in"] = 0
        params["tokens_out"] = 0
    return params


async def run_chat_turn(
    host: ChatHost,
    *,
    message: str,
    session_id: str | None,
    request_id: int,
) -> None:
    """Run one backend chat turn without transport-specific concerns."""
    log_event(
        logger,
        logging.INFO,
        "backend_chat_received",
        request_id=request_id,
        session_id=session_id or host.session_id,
        message_chars=len(message),
    )

    layer_used = 4

    if session_id and session_id != host.session_id:
        await host.teardown_agent_resources()
        host.session_id = session_id
        host.session_log_dir = setup_session_logging(
            host.config.logging,
            host.session_id,
        )
        host.session_approved_tools.clear()

    _emit_chat_ack(host, request_id)
    log_event(
        logger,
        logging.INFO,
        "backend_chat_ack",
        request_id=request_id,
        session_id=host.session_id,
    )

    heartbeat_stop = asyncio.Event()

    async def _chat_heartbeat() -> None:
        while True:
            try:
                await asyncio.wait_for(
                    heartbeat_stop.wait(),
                    timeout=_CHAT_HEARTBEAT_INTERVAL_S,
                )
                return
            except TimeoutError:
                _emit_chat_ack(host, request_id)
                log_event(
                    logger,
                    logging.DEBUG,
                    "backend_chat_heartbeat",
                    request_id=request_id,
                    session_id=host.session_id,
                )

    heartbeat_task = asyncio.create_task(_chat_heartbeat())

    try:
        if not host.session_titled:
            title = message[:60] + ("..." if len(message) > 60 else "")
            host.session_store.update_session(host.session_id, title=title)
            host.session_titled = True

        message = host.expand_file_mentions(message)

        layer_used, request_type_name, force_l4 = host.select_chat_layer(message)
        log_event(
            logger,
            logging.INFO,
            "backend_chat_route_selected",
            request_id=request_id,
            session_id=host.session_id,
            force_l4=force_l4,
            request_type=request_type_name,
            selected_layer=layer_used,
            has_l2_context=bool(host.context_assembler),
            has_l3_provider=bool(host.l3_provider),
        )

        if layer_used == 1:
            try:
                from autocode.layer1.queries import DeterministicQueryHandler

                handler = DeterministicQueryHandler(project_root=host.project_root)
                response = handler.handle(message)
                host.emit_notification("on_token", {"text": response.content})
                host.emit_notification(
                    "on_done",
                    {
                        **_done_params(host, 1),
                        "layer_used": 1,
                    },
                )
                return
            except ImportError:
                layer_used = 4

        log_event(
            logger,
            logging.INFO,
            "backend_chat_agent_loop_init_start",
            request_id=request_id,
            session_id=host.session_id,
        )
        try:
            agent_loop = host.ensure_agent_loop()
            agent_loop.session_id = host.session_id
        except Exception as exc:  # noqa: BLE001 - surface as frontend error
            logger.exception("Error initializing agent loop: %s", exc)
            host.emit_notification("on_error", {"message": str(exc)})
            host.emit_notification("on_done", _done_params(host, layer_used))
            return
        log_event(
            logger,
            logging.INFO,
            "backend_chat_agent_loop_init_done",
            request_id=request_id,
            session_id=host.session_id,
        )

        if layer_used == 2:
            try:
                from autocode.agent.tools import _code_index_cache
                from autocode.layer2.rules import RulesLoader
                from autocode.layer2.search import HybridSearch

                if _code_index_cache is None:
                    layer_used = 4
                else:
                    search = HybridSearch(_code_index_cache)
                    top_k = host.config.layer2.search_top_k
                    results = search.search(message, top_k=top_k)
                    rules_loader = RulesLoader()
                    rules_text = rules_loader.load(host.project_root)
                    assembled = host.context_assembler.assemble(
                        message,
                        rules=rules_text,
                        search_results=results,
                    )
                    log_event(
                        logger,
                        logging.INFO,
                        "backend_chat_layer2_start",
                        request_id=request_id,
                        session_id=host.session_id,
                    )
                    await agent_loop.run(
                        message,
                        on_chunk=lambda text: on_chunk(host, text),
                        on_thinking_chunk=lambda text: on_thinking_chunk(host, text),
                        on_retry_notice=lambda text: emit_warning(host, text),
                        on_tool_call=lambda tool_name, status, result="": on_tool_call(
                            host, tool_name, status, result
                        ),
                        approval_callback=lambda tool_name, arguments: approval_callback(
                            host, tool_name, arguments
                        ),
                        ask_user_callback=lambda question, options, allow_text: ask_user_callback(
                            host, question, options, allow_text
                        ),
                        reasoning_enabled=host.show_thinking,
                        injected_context=assembled,
                    )
                    emit_cost_limit_warning(host)
                    host.emit_cost_update()
                    host.emit_notification(
                        "on_done",
                        {
                            **_done_params(host, 2),
                            "layer_used": 2,
                        },
                    )
                    return
            except ImportError:
                layer_used = 4
            except Exception as exc:  # noqa: BLE001 - deliberate fallback to layer 4
                log_event(
                    logger,
                    logging.WARNING,
                    "backend_chat_layer2_fallback",
                    request_id=request_id,
                    session_id=host.session_id,
                    error=str(exc),
                )
                layer_used = 4

        if layer_used == 3:
            try:
                log_event(
                    logger,
                    logging.INFO,
                    "backend_chat_layer3_start",
                    request_id=request_id,
                    session_id=host.session_id,
                )
                result_text = await host.l3_provider.generate(message)
                host.session_store.add_message(host.session_id, "user", message)
                host.session_store.add_message(host.session_id, "assistant", result_text)
                host.emit_notification("on_token", {"text": result_text})
                host.emit_notification(
                    "on_done",
                    {
                        **_done_params(host, 3),
                        "layer_used": 3,
                    },
                )
                return
            except Exception as exc:  # noqa: BLE001 - deliberate fallback to layer 4
                log_event(
                    logger,
                    logging.WARNING,
                    "backend_chat_layer3_fallback",
                    request_id=request_id,
                    session_id=host.session_id,
                    error=str(exc),
                )
                layer_used = 4

        try:
            log_event(
                logger,
                logging.INFO,
                "backend_chat_layer4_start",
                request_id=request_id,
                session_id=host.session_id,
            )
            await agent_loop.run(
                message,
                on_chunk=lambda text: on_chunk(host, text),
                on_thinking_chunk=lambda text: on_thinking_chunk(host, text),
                on_retry_notice=lambda text: emit_warning(host, text),
                on_tool_call=lambda tool_name, status, result="": on_tool_call(
                    host, tool_name, status, result
                ),
                approval_callback=lambda tool_name, arguments: approval_callback(
                    host, tool_name, arguments
                ),
                ask_user_callback=lambda question, options, allow_text: ask_user_callback(
                    host, question, options, allow_text
                ),
                reasoning_enabled=host.show_thinking,
            )
        except asyncio.CancelledError:
            host.emit_cost_update()
            host.emit_notification("on_done", _done_params(host, layer_used, cancelled=True))
            return
        except Exception as exc:  # noqa: BLE001 - surface as frontend error
            logger.exception("Error in handle_chat: %s", exc)
            host.emit_notification("on_error", {"message": str(exc)})

        emit_cost_limit_warning(host)
        host.emit_cost_update()
        host.emit_notification("on_done", _done_params(host, layer_used))
    finally:
        heartbeat_stop.set()
        with contextlib.suppress(asyncio.CancelledError):
            await heartbeat_task
